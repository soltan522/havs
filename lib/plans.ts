import type { Locale } from "./i18n";
import { PREVIEWS } from "./previews.generated";
import RAW from "@/data/plans.json";

export type LocalizedText = Record<Locale, string>;

export type PlanStyle =
  | "modern"
  | "classic"
  | "minimal"
  | "coastal"
  | "chalet"
  | "farmhouse"
  | "luxury"
  | "compact"
  | "mediterranean"
  | "duplex";

export type Plan = {
  slug: string;
  style: PlanStyle;
  roof: "flat" | "hip" | "gable" | "aframe" | "shed";
  title: LocalizedText;
  summary: LocalizedText;
  areaM2: number;
  floors: number;
  bedrooms: number;
  bathrooms: number;
  garage: boolean;
  pool: boolean;
  priceCents: number;
  published: boolean;
  /** Sample plan: shown in the catalogue with concept sheets, but not sold online (no files yet). */
  demo: boolean;
  /** Full sheets / renders shown on the plan page. Generated by scripts/build-previews.mjs */
  gallery: string[];
  /** Cropped card images (drawing area only). */
  cover: string;
  hover: string;
  /** Object keys inside the PRIVATE Supabase bucket. */
  files: { pdf: string; dwg: string; cad: string };
};

type RawPlan = Omit<Plan, "gallery" | "files" | "cover" | "hover">;

// Catalogue lives in data/plans.json so the preview script can read the same data.
export const PLANS: Plan[] = (RAW as RawPlan[]).map((p) => ({
  ...p,
  gallery: PREVIEWS[p.slug]?.sheets ?? [],
  cover: PREVIEWS[p.slug]?.cover ?? "",
  hover: PREVIEWS[p.slug]?.hover ?? "",
  files: { pdf: `${p.slug}/plan.pdf`, dwg: `${p.slug}/plan.dwg`, cad: `${p.slug}/plan.cad` },
}));

