type SheetNames = { render: string; owner: string; image: string; site: string; elevation: string; axonometric: string; schedules: string; typical: string; lower: string; section: string; plans: string[] };

/** Human name of a gallery item, e.g. "First floor plan" for kind "plan-1", the lower ground floor plan for "lower". */
export function sheetName(names: SheetNames, kind: string): string {
  if (kind.startsWith("plan-")) return names.plans[Number(kind.slice(5))] ?? names.plans[names.plans.length - 1];
  return names[kind as keyof Omit<SheetNames, "plans">] ?? kind;
}

/** Gallery name of a sheet; a multi-unit project has a masterplan, a street / typical elevation and typical-house plans. */
export function planSheetName(c: (typeof COPY)[Locale], plan: Plan, kind: string): string {
  if (plan.interior) {
    const n = c.interior;
    const [what, li] = kind.split("-");
    const named: Record<string, string> = { plan: n.layout, finish: n.finish, ceiling: n.ceilingPlan, interior: n.elevations, cutaway: n.cutaway, materials: n.materials, schedules: n.schedules };
    const label = named[what] ?? sheetName(c.sheetNames, kind);
    // a two-level interior names the floor first
    return li !== undefined && plan.floors > 1 ? `${n.floors[Number(li)] ?? ""} — ${label.charAt(0).toLowerCase()}${label.slice(1)}` : label;
  }
  const base = sheetName(c.sheetNames, kind);
  if (!plan.project) return base;
  const p = c.project.sheets;
  if (kind === "site") return p.site;
  if (kind === "axonometric") return p.axonometric;
  if (plan.style === "showroom" && kind === "plan-1") return p.mezzanine;
  if (plan.project.units === 1) return base;
  if (kind === "elevation") return plan.project.kind === "row" ? p.street : p.elevation;
  if (kind.startsWith("plan-")) return `${c.project.typical}: ${base.charAt(0).toLowerCase()}${base.slice(1)}`;
  return base;
}

/** Card line: "240 m² · 2 floors · 4 bedrooms", or "7 × 180 m² · …" for a project. */
export function specsLine(lang: Locale, plan: Plan): string {
  if (plan.interior) return `${areaText(plan)} · ${PALETTE_LABELS[plan.interior.palette][lang]}${plan.bedrooms ? ` · ${plan.bedrooms} ${UI[lang].bedrooms.toLowerCase()}` : ""}`;
  const p = COPY[lang].project;
  // the figure a buyer compares first: guest rooms, seats, flats, else parking
  if (plan.rooms) return `${areaText(plan)} · ${floorsText(lang, plan.floors, UI[lang].floors)} · ${plan.rooms} ${p.roomsShort}`;
  if (plan.seats) return `${areaText(plan)} · ${floorsText(lang, plan.floors, UI[lang].floors)} · ${plan.seats} ${p.seatsShort}`;
  if (plan.flats) return `${areaText(plan)} · ${floorsText(lang, plan.floors, UI[lang].floors)} · ${plan.flats} ${p.flatsShort}`;
  if (isCommercial(plan)) return `${areaText(plan)} · ${floorsText(lang, plan.floors, UI[lang].floors)} · ${plan.parking ?? 0} ${p.parkingShort}`;
  return `${areaText(plan)} · ${floorsText(lang, plan.floors, UI[lang].floors)} · ${plan.bedrooms} ${UI[lang].bedrooms.toLowerCase()}`;
}

/** "2 floors" / "1 floor" in the current language (AZ and RU labels do not change for the counts we use). */
export function floorsText(lang: Locale, n: number, label: string): string {
  if (lang === "en") return `${n} ${n === 1 ? "floor" : "floors"}`;
  return `${n} ${label.toLowerCase()}`;
}
